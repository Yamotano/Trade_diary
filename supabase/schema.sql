-- ---------- Таблицы ----------
create table if not exists public.accounts (
  id              bigint generated by default as identity primary key,
  user_id         uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name            text not null check (char_length(trim(name)) between 1 and 60),
  broker          text not null default '',
  currency        text not null default 'RUB' check (currency ~ '^[A-Z]{3}$'),
  initial_balance numeric not null default 0,
  created_at      timestamptz not null default now()
);

create table if not exists public.instruments (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null default auth.uid() references auth.users (id) on delete cascade,
  symbol      text not null,
  name        text not null default '',
  exchange    text not null default '',
  type        text not null default 'future',
  point_value numeric not null check (point_value > 0),
  tick_size   numeric check (tick_size > 0),
  margin      numeric,
  fee         numeric not null default 0 check (fee >= 0),
  unique (user_id, symbol)
);

create table if not exists public.trades (
  id            bigint generated by default as identity primary key,
  user_id       uuid not null default auth.uid() references auth.users (id) on delete cascade,
  account_id    bigint not null references public.accounts (id) on delete cascade,
  symbol        text not null,
  side          text not null check (side in ('long', 'short')),
  qty           numeric not null check (qty > 0),
  entry_price   numeric not null check (entry_price > 0),
  exit_price    numeric check (exit_price > 0),
  entry_time    timestamp not null,
  exit_time     timestamp,
  fees          numeric not null default 0 check (fees >= 0),
  funding       numeric not null default 0,
  point_value   numeric not null check (point_value > 0),
  tick_size     numeric,
  stop_price    numeric,
  target_price  numeric,
  setup         text not null default '',
  tags          text not null default '',
  mistakes      text not null default '',
  emotion       text not null default '',
  rating        integer check (rating between 1 and 5),
  notes         text not null default '',
  screenshot    text not null default ''
);

create table if not exists public.journal (
  id      bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  date    date not null,
  mood    integer check (mood between 1 and 5),
  plan    text not null default '',
  review  text not null default '',
  notes   text not null default '',
  unique (user_id, date)
);

create table if not exists public.cashflows (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null default auth.uid() references auth.users (id) on delete cascade,
  account_id bigint not null references public.accounts (id) on delete cascade,
  date       date not null,
  amount     numeric not null,
  note       text not null default ''
);

create index if not exists idx_trades_user_exit on public.trades (user_id, exit_time desc);
create index if not exists idx_trades_account on public.trades (account_id);
create index if not exists idx_journal_user_date on public.journal (user_id, date desc);
create index if not exists idx_cashflows_account on public.cashflows (account_id);
create index if not exists idx_accounts_user on public.accounts (user_id);
create index if not exists idx_instruments_user on public.instruments (user_id);
create index if not exists idx_cashflows_user on public.cashflows (user_id);

-- ---------- Row Level Security ----------
alter table public.accounts    enable row level security;
alter table public.instruments enable row level security;
alter table public.trades      enable row level security;
alter table public.journal     enable row level security;
alter table public.cashflows   enable row level security;

drop policy if exists accounts_owner on public.accounts;
create policy accounts_owner on public.accounts
  for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

drop policy if exists instruments_owner on public.instruments;
create policy instruments_owner on public.instruments
  for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

-- Сделка должна ссылаться на счёт того же пользователя.
drop policy if exists trades_owner on public.trades;
create policy trades_owner on public.trades
  for all to authenticated
  using (
    user_id = auth.uid()
    and exists (
      select 1 from public.accounts a
      where a.id = trades.account_id and a.user_id = auth.uid()
    )
  )
  with check (
    user_id = auth.uid()
    and exists (
      select 1 from public.accounts a
      where a.id = trades.account_id and a.user_id = auth.uid()
    )
  );

drop policy if exists journal_owner on public.journal;
create policy journal_owner on public.journal
  for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

drop policy if exists cashflows_owner on public.cashflows;
create policy cashflows_owner on public.cashflows
  for all to authenticated
  using (
    user_id = auth.uid()
    and exists (
      select 1 from public.accounts a
      where a.id = cashflows.account_id and a.user_id = auth.uid()
    )
  )
  with check (
    user_id = auth.uid()
    and exists (
      select 1 from public.accounts a
      where a.id = cashflows.account_id and a.user_id = auth.uid()
    )
  );

-- ---------- Права для авторизованных ----------
grant usage on schema public to authenticated;
grant select, insert, update, delete on public.accounts, public.instruments, public.trades, public.journal, public.cashflows to authenticated;
grant usage, select on all sequences in schema public to authenticated;

